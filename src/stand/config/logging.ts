/**
 * Куда уходит журнал прохождений.
 *
 * Единственное место хранения — Google-таблица: веб-приложение Apps Script
 * принимает POST и дописывает строку. В браузере ничего не остаётся, так
 * что прогоны со всех устройств сразу лежат в одном месте, и никто не
 * забудет ничего выгрузить перед тем, как почистить данные сайта.
 *
 * Обратная сторона: не ушедшая строка теряется. Поэтому отправка повторяется
 * трижды, а если не вышло — экран благодарности говорит об этом прямо и
 * даёт скопировать строку руками. Модератор в этот момент ещё перед
 * экраном, а респондент ещё в комнате.
 *
 * Адрес берётся из переменной окружения сборки `VITE_STAND_LOG_URL`, а если
 * её нет — из константы ниже. Разница в том, кто видит адрес: константа
 * лежит в публичном репозитории, переменная окружения задаётся в настройках
 * сборки. Адрес Apps Script — открытая точка записи, так что писать в
 * таблицу сможет любой, кто откроет исходники. Для стенда это терпимо:
 * мусорные строки видно по колонкам, а таблицу можно пересоздать. Если
 * станет неудобно — развернуть новую версию скрипта и убрать адрес в
 * переменную окружения, код для этого менять не нужно.
 */
const FALLBACK_LOG_URL =
  'https://script.google.com/macros/s/AKfycbzawb9Da2r2_uqDeljbptJILGXAo4Wd6lSfp4eVpEm6lzfeYb_lF3inaIxB9i8vWsHALA/exec'

export const standLogUrl: string =
  (import.meta.env.VITE_STAND_LOG_URL as string | undefined) || FALLBACK_LOG_URL

/** Сколько раз пробуем отправить строку, прежде чем признать неудачу. */
export const standLogAttempts = 3
