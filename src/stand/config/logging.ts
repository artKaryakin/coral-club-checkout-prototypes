/**
 * Куда уходит журнал прохождений.
 *
 * Стенд лежит на GitHub Pages — это статика, писать в файл репозитория из
 * браузера она не может. Поэтому журнал живёт в два слоя:
 *
 *  1. localStorage браузера — работает всегда, ничего настраивать не надо,
 *     виден на экране `#/log`, выгружается в CSV;
 *  2. Google-таблица — если задан адрес веб-приложения Apps Script, каждое
 *     прохождение уходит туда строкой. Тогда прогоны со всех устройств
 *     собираются в одном месте сами.
 *
 * Второй слой необязателен: с пустым адресом стенд работает как обычно,
 * просто ничего никуда не отправляет. Ошибка отправки тоже ничего не ломает
 * — строка остаётся в браузере с пометкой «не отправлено», и её можно
 * отправить повторно с экрана журнала.
 *
 * Адрес берётся из переменной окружения сборки `VITE_STAND_LOG_URL`, а если
 * её нет — из константы ниже. Разница в том, кто видит адрес: константа
 * лежит в публичном репозитории, переменная окружения задаётся в настройках
 * сборки. Адрес Apps Script — это открытая точка записи, так что если
 * положить его в код, писать в таблицу сможет любой, кто откроет исходники.
 * Для стенда это терпимо, для чего-то большего — нет.
 */
const FALLBACK_LOG_URL = ''

export const standLogUrl: string =
  (import.meta.env.VITE_STAND_LOG_URL as string | undefined) || FALLBACK_LOG_URL

/** Сколько прохождений держим в браузере. Дальше вытесняются самые старые. */
export const standLogLimit = 500
