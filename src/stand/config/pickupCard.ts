import type { PickupProviderCode } from './types'

/**
 * Строки карточки пункта выдачи.
 *
 * Карточка собирала их сама, и собирала неверно. Срок брался курьерский
 * («2–3 рабочих дня») — хотя у самовывоза свой, он лежит в
 * `delivery.pickup.eta` и именно его показывает прод-версия. Цена нуля
 * печаталась как «0 ₽» и «$0»: в списке пунктов проверка на бесплатность
 * была, в карточке — нет. А под заголовком «Как добраться» стоял текст про
 * срок хранения заказа: своего текста про дорогу в проекте не было вовсе, и
 * заголовок занял единственное свободное поле.
 *
 * Поэтому строки собираются здесь, а не в вёрстке: их три, они зависят от
 * типа пункта, и у двух концептов они обязаны совпадать — иначе респондент
 * сравнивает не способы ввода адреса, а два разных описания одного пункта.
 *
 * Тексты про дорогу — по типу пункта, а не по адресу. Двадцать четыре точки
 * на шесть рынков; настоящего маршрута до настоящего адреса мы всё равно не
 * знаем, а в тесте важно, что подсказка на этом месте есть и читается.
 */
export interface PickupCardLines {
  /** Когда заказ можно забрать. */
  eta: string

  /**
   * Сколько заказ ждёт получателя. Только у пунктов службы: в офис человек
   * приходит к себе, и срок там другой — пока не подтвердим какой, строки
   * нет совсем (лучше без неё, чем с чужими семью днями).
   */
  storage?: string

  /** Как дойти от входа. */
  directions: string
}

type Translate = (key: string, params?: Record<string, string>) => string

export function pickupCardLines(
  provider: PickupProviderCode,
  translate: Translate,
): PickupCardLines {
  if (provider === 'office') {
    return {
      eta: translate('pickup.card.office'),
      directions: translate('pickup.directions.office'),
    }
  }

  return {
    // Число дней — из того же ключа, что у прод-версии: срок самовывоза
    // меняется в одном месте, а не в каждой подписи отдельно.
    eta: translate('pickup.card.eta', { eta: translate('delivery.pickup.eta') }),
    storage: translate('pickup.card.storage'),
    directions: translate('pickup.directions.point'),
  }
}
