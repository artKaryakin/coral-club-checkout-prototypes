/**
 * Пауза после отказа сервиса подсказок.
 *
 * Photon на photon.komoot.io — демо-сервер самого проекта, и в его условиях
 * прямо сказано: «extensive usage will be throttled or completely banned».
 * Клиенты к нему ходят не чаще раза в секунду; у нас пауза после ввода
 * 500 мс, плюс обратное геокодирование на каждое касание карты, плюс шесть
 * рынков и две версии чекаута в одной сессии. За интервью с одного адреса
 * уходят сотни запросов, и в какой-то момент сервер перестаёт отвечать.
 *
 * Дальше важное: пока он отказывает, каждое нажатие клавиши уходило к нему
 * снова и загоняло отказ глубже. Поэтому после первой неудачи мы перестаём
 * ходить к сервису и сразу отдаём запасной список — ровно то же, что
 * человек увидел бы после ожидания, но без ожидания.
 *
 * Пауза короткая: отказ бывает и разовым, и держать подсказки выключенными
 * всю сессию из-за одной сетевой осечки незачем.
 *
 * Состояние на уровне модуля: у каждого поля формы свой экземпляр
 * useAddressSuggest, а сервис один на всех, и знать об отказе должны все.
 */
const COOLDOWN_MS = 30_000

let coolingUntil = 0

/** Сервис недавно отказал — идти к нему сейчас незачем. */
export function isSuggestCoolingDown(): boolean {
  return Date.now() < coolingUntil
}

export function startSuggestCooldown(): void {
  coolingUntil = Date.now() + COOLDOWN_MS
}

/** Смена прогона не должна тащить за собой отказ прошлого. */
export function resetSuggestCooldown(): void {
  coolingUntil = 0
}
